FONT_HDR   = Font(name='맑은 고딕', size=12, bold=True, color='FFFFFF')
FONT_SUB   = Font(name='맑은 고딕', size=12, bold=True, italic=True)

# 정렬: 원본 기준
# center+center : No, Unit, Category, Type, FM, SG, S, O, D, RPN, Countermeasure-required
# left+center   : IntfName, Detail, EffectModule, EffectSystem, PreventiveAction, DetectionAction, TestMethod, Countermeasure 등
ALIGN_C  = Alignment(horizontal='center', vertical='center', wrap_text=True)
ALIGN_L  = Alignment(horizontal='left',   vertical='center', wrap_text=True)
ALIGN_CX = Alignment(horizontal='center', vertical='center', wrap_text=False)  # 단순 중앙

# 컬럼별 정렬 매핑
COL_ALIGN = {
    1: ALIGN_C, 2: ALIGN_C, 3: ALIGN_C, 4: ALIGN_L, 5: ALIGN_C,
    6: ALIGN_C, 7: ALIGN_L, 8: ALIGN_L, 9: ALIGN_L, 10: ALIGN_C,
    11: ALIGN_C, 12: ALIGN_L, 13: ALIGN_C, 14: ALIGN_L, 15: ALIGN_L,
    16: ALIGN_C, 17: ALIGN_C, 18: ALIGN_C, 19: ALIGN_L,
    20: ALIGN_C, 21: ALIGN_C, 22: ALIGN_C, 23: ALIGN_C,
    24: ALIGN_C, 25: ALIGN_L, 26: ALIGN_L, 27: ALIGN_C,
}

# 단순 행(REVERSE/NO/AS WELL AS 등): 행 높이 자동(None)
SIMPLE_HAZOPS = {'REVERSE', 'NO', 'AS WELL AS', 'PART OF', 'EARLY', 'LATE'}
DATA_ROW_H = 38.4   # 원본 데이터 행 높이

# ──────────────────────────────────────────────────────────────────────────────
# 메인 처리
# ──────────────────────────────────────────────────────────────────────────────
print("템플릿 로드 중...")
wb = openpyxl.load_workbook(SRC)
ws = wb['SW_FMEA']

# 열 너비: 원본 템플릿과 동일
COL_WIDTHS = {
    1: 13.5, 2: 18.5, 3: 20.5, 4: 40.1, 5: 62.7,
    6: 22.6, 7: 45.2, 8: 41.1, 9: 13.0, 10: 20.6,
    11: 11.0, 12: 74.6, 13: 7.5, 14: 99.0, 15: 58.5,
    16: 7.5, 17: 13.0, 18: 32.0, 19: 45.9,
    20: 7.5, 21: 13.0, 22: 13.0, 23: 13.0,
    24: 20.0, 25: 20.0, 26: 28.1, 27: 23.2,
}
for col, width in COL_WIDTHS.items():
    ws.column_dimensions[get_column_letter(col)].width = width

def write_cell(ws, row, col, value, align=None):
    cell = ws.cell(row, col)
    cell.value = value
    cell.border = make_border()
    cell.font = FONT_FM if col == 6 else FONT_DATA
    cell.alignment = align or COL_ALIGN.get(col, ALIGN_L)

# ── 헤더 행 (Row 12) 스타일 ────────────────────────────────────────────────
HDR_FILL = make_fill('4472C4')
for col in range(1, 28):
    cell = ws.cell(12, col)
    if cell.value:
        cell.font = FONT_HDR
        cell.fill = HDR_FILL
        cell.border = make_border()
        cell.alignment = ALIGN_C

# Row 13 sub-header (Safety Mechanism / Test Method)
ws.cell(13, 14).value = "Safety Mechanism"
ws.cell(13, 15).value = "Test Method"
for col in range(1, 28):
    cell = ws.cell(13, col)
    cell.font = FONT_SUB
    cell.fill = make_fill('D9E1F2')
    cell.border = make_border()
    cell.alignment = ALIGN_C

# ── 인터페이스 번호 매핑 (data_only로 수식 결과 읽기) ─────────────────────────
print("인터페이스 번호 매핑 중...")
wb_ro = openpyxl.load_workbook(SRC, read_only=True, data_only=True)
ws_ro = wb_ro['SW_FMEA']
row_to_no = {}  # {row_number: interface_no}
current_intf_no = None
for r in range(14, 5000):
    no_val = ws_ro.cell(r, 1).value
    fail_val = ws_ro.cell(r, 6).value
    detail_val = ws_ro.cell(r, 7).value
    if no_val is not None:
        try:
            current_intf_no = int(float(no_val))
        except (ValueError, TypeError):
            pass
    if current_intf_no is not None:
        row_to_no[r] = current_intf_no
    if r > 200 and no_val is None and fail_val is None and detail_val is None:
        break
wb_ro.close()
print(f"  {len(row_to_no)}개 행 매핑 완료, 인터페이스 {current_intf_no}개 까지")

# ── 데이터 처리 ───────────────────────────────────────────────────────────────
print("데이터 처리 중...")
max_row = ws.max_row

current_no = None
current_fail = None

for r in range(14, max_row + 50):
    no_val = ws.cell(r, 1).value
    fail_val = ws.cell(r, 6).value
    detail_val = ws.cell(r, 7).value

    # 인터페이스 번호는 매핑 테이블에서 참조 (수식 결과값)
    if r in row_to_no:
        current_no = row_to_no[r]

    if fail_val is not None:
        current_fail = str(fail_val).strip()

    if detail_val is None and fail_val is None and no_val is None:
        if r > max_row:
            break
        continue

    # ── 모든 기존 셀에 원본 스타일 적용 (cols 1-7: 기존 데이터 유지) ──────────
    for col in range(1, 28):
        cell = ws.cell(r, col)
        cell.border = make_border()
        cell.font = FONT_FM if col == 6 else FONT_DATA
        cell.alignment = COL_ALIGN.get(col, ALIGN_L)
        cell.fill = NO_FILL  # 배경색 없음 (원본 동일)

    # ── 분석 데이터 채우기 - HAZOP 키워드 첫 행에만 ─────────────────────────
    if fail_val is not None and current_no in ANALYSIS:
        analysis_key = str(fail_val).strip()
        if analysis_key in ANALYSIS[current_no]:
            data = ANALYSIS[current_no][analysis_key]
            eff_mod, eff_sys, eff_sg, s, o, pa, da, d = data

            write_cell(ws, r, 8, eff_mod)
            write_cell(ws, r, 9, eff_sys)
            write_cell(ws, r, 10, eff_sg)

            if s is not None:
                write_cell(ws, r, 11, s)
                write_cell(ws, r, 12, pa)
                write_cell(ws, r, 13, o)
                write_cell(ws, r, 14, da)
                write_cell(ws, r, 16, d)
                write_cell(ws, r, 17, s * o * d)
                write_cell(ws, r, 18, "NO")
        else:
            # REVERSE, NO, AS WELL AS 등 N/A 행: Effect on SG = 'x'
            write_cell(ws, r, 10, NA)

    # ── 행 높이 설정 ────────────────────────────────────────────────────────
    if current_fail in SIMPLE_HAZOPS and fail_val is not None:
        # REVERSE/NO 등 단순 행: 원본에서 None(자동) 사용
        ws.row_dimensions[r].height = None
    else:
        ws.row_dimensions[r].height = DATA_ROW_H

print("저장 중...")
wb.save(DST)
print(f"\nLQ2 SW FMEA 완성: {DST}")
print(f"총 {max_row - 13}개 행 처리 완료")
